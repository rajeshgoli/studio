// Run with PLAYWRIGHT_MODULE and STUDIO_TEST_PYTHON when not on PATH.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {spawn}=require('node:child_process');
const {once}=require('node:events');
const assert=require('node:assert/strict');
(async()=>{
 const child=spawn(process.env.STUDIO_TEST_PYTHON||'python3',['-m','server.tests.local_browser_fixture'],{stdio:['pipe','pipe','inherit']});
 let browser;
 try{
 const [line]=await once(child.stdout,'data');const {port}=JSON.parse(line.toString());
 const base='http://localhost:'+port;
 browser=await chromium.launch({headless:true});
 const context=await browser.newContext();
 await context.grantPermissions(['local-network-access'],{origin:'https://viewer.example'});
 const page=await context.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 let remoteWrites=0;
 await page.route('https://viewer.example/**',async route=>{
  const request=route.request();if(request.method()==='POST')remoteWrites++;
  const u=new URL(request.url());
  const response=await context.request.fetch(base+u.pathname+u.search,{method:request.method(),headers:{Host:'viewer.example','Cf-Access-Jwt-Assertion':'browser-test-owner'}});
  await route.fulfill({response});
 });
 await page.goto('https://viewer.example/');
 await page.getByText('Connected to this recording Mac. Choose a production to open its room.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Open singing room'}).click();
 const sing=page.frameLocator('iframe');
 await sing.getByRole('heading',{name:'Singing Studio · Test'}).waitFor();
 await sing.locator('#stage').filter({hasText:'idle'}).waitFor();
 await sing.getByRole('tab',{name:'Setup',exact:true}).click();
 await sing.locator('#setup-pane').hover();await page.mouse.wheel(0,350);
 await sing.locator('#mode').focus();await page.keyboard.press('ArrowDown');
 await page.waitForTimeout(300);
 assert.match(await sing.locator('#stage').textContent(),/^idle/);
 await page.screenshot({path:'/tmp/st20-setup.png',fullPage:true});
 await sing.getByRole('tab',{name:'Record',exact:true}).click();
 // Recording fills the viewport; no viewer navigation competes with the wheel.
 assert.equal(await page.locator('body > header').isVisible(),false);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight),true);
 const frameBounds=await page.locator('iframe').boundingBox();
 assert.equal(Math.round(frameBounds.y+frameBounds.height),720);
 await page.locator('#room-toolbar').hover();await page.mouse.wheel(0,300);
 await page.waitForTimeout(300);
 assert.match(await sing.locator('#stage').textContent(),/^idle/);
 await sing.locator('#lyr').evaluate(el=>{const long=document.createElement('div');long.style.height='1500px';el.append(long);});
 await sing.locator('#lyr').hover();await page.mouse.wheel(0,300);
 await page.waitForTimeout(300);
 assert.match(await sing.locator('#stage').textContent(),/^idle/);
 assert.ok(await sing.locator('#lyr').evaluate(el=>el.scrollTop)>0);
 // Wheel on the recording surface still deliberately starts a take.
 await sing.locator('h1').hover();await page.mouse.wheel(0,100);
 await sing.locator('#stage').filter({hasText:'rolling'}).waitFor();
 await sing.locator('#go').click();
 await sing.locator('#stage').filter({hasText:'singing'}).waitFor();
 await page.keyboard.press('ArrowRight');
 await sing.getByRole('button',{name:'Stop',exact:true}).waitFor();
 await page.keyboard.press('ArrowLeft');
 await sing.getByRole('button',{name:'Next line',exact:true}).waitFor();
 await page.keyboard.press('ArrowRight');
 await sing.getByRole('button',{name:'Stop',exact:true}).waitFor();
 // Focus is still on the main action: Enter invokes it only once.
 await page.keyboard.press('Enter');
 await sing.getByRole('tab',{name:'Saved takes',exact:true}).click();
 await sing.getByRole('button',{name:'Load playback'}).click();
 await sing.locator('audio[src^="blob:"]').waitFor();
 await sing.locator('#takes').evaluate(el=>{const long=document.createElement('div');long.style.height='800px';el.append(long);});
 await sing.locator('#takes').hover();await page.mouse.wheel(0,250);
 await page.waitForTimeout(300);
 assert.match(await sing.locator('#stage').textContent(),/^idle/);
 assert.ok(await sing.locator('#takes').evaluate(el=>el.scrollTop)>0);
 await page.screenshot({path:'/tmp/st20-takes.png',fullPage:true});
 await sing.getByRole('tab',{name:'Record',exact:true}).click();
 await page.screenshot({path:'/tmp/st20-singing.png',fullPage:true});
 await page.setViewportSize({width:1024,height:640});
 const controlBounds=await sing.locator('#go').boundingBox();
 assert.ok(controlBounds.y+controlBounds.height<=640,'record control fits shorter window');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight),true);
 await page.screenshot({path:'/tmp/st20-small.png',fullPage:true});
 await page.setViewportSize({width:1280,height:720});
 await page.getByRole('button',{name:'Back to productions'}).click();
 await page.locator('body > header').waitFor({state:'visible'});
 await page.locator('iframe').waitFor({state:'detached'});
 await page.getByRole('button',{name:'Return to room'}).click();
 await page.frameLocator('iframe').locator('#stage').filter({hasText:'idle'}).waitFor();
 await sing.locator('#pv').click();
 await sing.locator('#stage').filter({hasText:'preview'}).waitFor();
 await page.keyboard.press('Escape');
 await sing.locator('#stage').filter({hasText:'idle'}).waitFor();
 await sing.locator('#go').click();
 await sing.locator('#stage').filter({hasText:'rolling'}).waitFor();
 await page.keyboard.press('Escape');
 await sing.locator('#stage').filter({hasText:'idle'}).waitFor();
 await page.getByRole('button',{name:'Close room',exact:true}).click();
 await page.locator('iframe').waitFor({state:'detached'});
 await page.getByRole('button',{name:'Open talking room'}).click();
 const talk=page.frameLocator('iframe');
 await talk.locator('#partsel').waitFor();
 await talk.locator('#partsel').selectOption('body');
 await talk.locator('.line').filter({hasText:'body first line'}).first().waitFor();
 assert.equal(await talk.locator('#partsel').inputValue(),'body');
 await talk.locator('#partsel').selectOption('all');
 await talk.locator('.line').filter({hasText:'intro first line'}).first().waitFor();
 assert.equal(await talk.locator('#partsel').inputValue(),'all');
 await talk.locator('#reh').check();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight),true);
 await page.locator('#room-toolbar').hover();await page.mouse.wheel(0,300);
 await page.waitForTimeout(300);
 assert.match(await talk.locator('#stage').textContent(),/^Ready/);
 await page.screenshot({path:'/tmp/st20-talking.png',fullPage:true});
 await page.getByRole('button',{name:'Close room',exact:true}).click();
 await page.locator('iframe').waitFor({state:'detached'});
 assert.equal(remoteWrites,0,'recording commands must not use the public route');
 assert.deepEqual(errors,[]);
 // A different computer (local probe unavailable) stays a viewer.
 await page.route(base+'/**',route=>route.abort());
 await page.reload();
 await page.getByText(/Viewing only: could not connect/).waitFor();
 assert.equal(await page.getByRole('button',{name:'Open singing room'}).isDisabled(),true);
 await page.screenshot({path:'/tmp/st17-remote.png',fullPage:true});
 await page.unroute(base+'/**');
 // The direct localhost entry works without cross-origin configuration.
 await page.goto(base+'/song/test');
 await page.getByText('Connected to this recording Mac. Choose a production to open its room.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Open singing room'}).click();
 await page.frameLocator('iframe').getByRole('heading',{name:'Singing Studio · Test'}).waitFor();
 await page.getByRole('button',{name:'Close room',exact:true}).click();
 console.log('PASS: public URL direct singing/talking, remote fallback, localhost entry; no public writes or browser errors');
 }finally{if(browser)await browser.close();child.stdin.end();await once(child,'exit');}
})().catch(e=>{console.error(e);process.exitCode=1;});
